from pathlib import Path
from typing import List, Dict, Any

import joblib
import numpy as np
from tensorflow import keras

from .interfaces import RankingModelInterface


class KerasRankingModel(RankingModelInterface):
    """
    Keras-based employee assignment ranking model.

    Takes the feature dictionaries generated by FeatureBuilder,
    applies the same preprocessing used during model training,
    and returns the predicted probability of successful resolution.
    """

    MODEL_VERSION = "keras-assignment-v1"

    MODEL_FEATURES = [
        "skill_proficiency",
        "experience_years",
        "historical_success_rate",
        "average_resolution_hours",
        "sla_success_rate",
        "distance_km",
        "workload_ratio",
        "priority",
    ]

    def __init__(self):
        base_dir = Path(__file__).resolve().parent

        model_path = (
            base_dir / "helpdesk_assignment_model.keras"
        )

        preprocessor_path = (
            base_dir / "helpdesk_preprocessor.pkl"
        )

        if not model_path.exists():
            raise FileNotFoundError(
                f"Keras model not found: {model_path}"
            )

        if not preprocessor_path.exists():
            raise FileNotFoundError(
                f"Preprocessor not found: {preprocessor_path}"
            )

        self.model = keras.models.load_model(
            model_path
        )

        self.preprocessor = joblib.load(
            preprocessor_path
        )

    def get_model_name(self) -> str:
        return self.MODEL_VERSION

    def rank_candidates(
        self,
        candidates_features: List[Dict[str, Any]]
    ) -> List[float]:

        if not candidates_features:
            return []

        # Build the exact feature structure used during training.
        rows = []

        for candidate in candidates_features:

            row = {
                "skill_proficiency": candidate.get(
                    "skill_proficiency",
                    candidate.get("domain_proficiency", 3)
                ),

                "experience_years": candidate.get(
                    "experience_years",
                    1
                ),

                "historical_success_rate": candidate.get(
                    "historical_success_rate",
                    1.0
                ),

                "average_resolution_hours": candidate.get(
                    "average_resolution_hours",
                    candidate.get(
                        "average_resolution_time",
                        24 * 60
                    ) / 60.0
                ),

                "sla_success_rate": candidate.get(
                    "sla_success_rate",
                    1.0
                ),

                "distance_km": candidate.get(
                    "distance_km",
                    1.0
                ),

                "workload_ratio": candidate.get(
                    "workload_ratio",
                    0.0
                ),

                "priority": self._normalize_priority(
                    candidate.get(
                        "priority",
                        "NORMAL"
                    )
                ),
            }

            rows.append(row)

        import pandas as pd

        feature_df = pd.DataFrame(
            rows,
            columns=self.MODEL_FEATURES
        )

        # Apply the EXACT preprocessor fitted in Colab.
        processed_features = self.preprocessor.transform(
            feature_df
        )

        # Predict probability of successful resolution.
        probabilities = self.model.predict(
            processed_features,
            verbose=0
        ).reshape(-1)

        return [
            round(
                float(np.clip(probability, 0.0, 1.0)),
                4
            )
            for probability in probabilities
        ]

    @staticmethod
    def _normalize_priority(priority: Any) -> str:
        """
        Convert Django priority values into the categorical
        values used by the Colab training pipeline.
        """

        priority = str(priority).upper()

        priority_map = {
            "LOW": "Low",
            "NORMAL": "Normal",
            "HIGH": "High",
            "URGENT": "Urgent",
            "CRITICAL": "Critical",
        }

        return priority_map.get(
            priority,
            "Normal"
        )